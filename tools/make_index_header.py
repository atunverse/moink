#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""把 page/index.html（零注释成品页）内嵌成 src/index_html.h（改页必跑，漏跑会静默打进旧页面）。

★ 成品页与测试页已分开：
    page/index.html       零注释，供本脚本固化进固件 / OTA 热更
    page/index.dev.html   保留注释，供门禁、截图与逐行调试
  本脚本会拒绝含注释的页面，避免把测试页误固化进固件。

输出符号：
    static const unsigned char index_html_gz[]    = { ... };   /* gzip 压缩后的页面 */
    static const unsigned int  index_html_gz_len  = NNN;
    static const unsigned int  index_html_raw_len = MMM;       /* 压缩前的原始长度，仅用于日志 */

★ 为什么固化 gzip 而不是原始字节（2026-11-16 定）：
    页面 238 KB 直接发，实测把设备堆吃到只剩 132 B —— 手机浏览器一开就是
    4~6 条并发连接，每条连接 lwIP 要 5.7 KB 发送缓冲 + 5.7 KB 接收窗，
    叠上 238 KB 的大响应，堆很快被榨干，之后就再也打不开网页。
    gzip 后约 55 KB：手机端流量降到 1/4，固件 flash 一次省下 180+ KB，
    是「体积」和「内存」同时受益的唯一改法。手机浏览器都发 Accept-Encoding: gzip。

★ R1.2.0（FB-015）：固化前先断言「页面 meta 版本 == src/version.h 的 MOINK_VERSION」。
   版本号统一成一套之后，两处一旦漂移就又变回两套号 —— 这个断言就是防漂移闸门，
   不一致直接 exit 1，并打印两边实际值。
"""
import gzip
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "page", "index.html")
VH = os.path.join(ROOT, "src", "version.h")
DST = os.path.join(ROOT, "src", "index_html.h")

META_RE = re.compile(r'<meta\s+name="moink-page-version"\s+content="([^"]+)"')
VER_RE = re.compile(r'#define\s+MOINK_VERSION\s+"([^"]+)"')


def main():
    data = open(SRC, "rb").read()
    text = data.decode("utf-8")

    # accept="image/*" / "font/*" 是 MIME 通配符，不能按裸 "/*" 判注释
    if "<!--" in text or re.search(r"/\*[\s\S]*?\*/", text):
        print("!! 固化的是成品页，必须零注释；请先跑 python page/build.py")
        print("   （不要直接固化 page/index.dev.html，那是保留注释的测试页）")
        return 1

    m_page = META_RE.search(text)
    m_hdr = VER_RE.search(open(VH, encoding="utf-8").read())
    if not m_page or not m_hdr:
        print("!! 版本号取不到：页面 meta=%s / version.h MOINK_VERSION=%s"
              % (bool(m_page), bool(m_hdr)))
        return 1
    page_ver, hdr_ver = m_page.group(1), m_hdr.group(1)
    if page_ver != hdr_ver:
        print("!! 版本号不一致，拒绝固化：")
        print("     page/index.html  <meta moink-page-version> = %s" % page_ver)
        print("     src/version.h    MOINK_VERSION              = %s" % hdr_ver)
        print("   统一版本号之后两处必须相同，改齐再跑。")
        return 1

    raw = len(data)
    gz = gzip.compress(data, 9, mtime=0)      # mtime=0：同样输入永远同样输出，便于比对
    n = len(gz)

    lines = []
    lines.append("/* auto-generated by tools/make_index_header.py - do not edit */")
    lines.append("/* page/index.html %d B -> gzip %d B (%.0f%%) */"
                 % (raw, n, n * 100.0 / raw))
    lines.append("static const unsigned char index_html_gz[] = {")
    for i in range(0, n, 16):
        chunk = gz[i:i + 16]
        lines.append("    " + ",".join("0x%02x" % b for b in chunk) + ",")
    lines.append("};")
    lines.append("static const unsigned int index_html_gz_len  = %d;" % n)
    lines.append("static const unsigned int index_html_raw_len = %d;" % raw)
    lines.append("")

    open(DST, "w", encoding="ascii", newline="\n").write("\n".join(lines))
    print("wrote %s (%d B -> gzip %d B, ver %s) -> %s" % (SRC, raw, n, hdr_ver, DST))
    return 0


if __name__ == "__main__":
    sys.exit(main())
